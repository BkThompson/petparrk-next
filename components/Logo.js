//
// Sizing: pass a height. The full lockup is 4.58:1, so a 26px-tall logo is
// about 119px wide; the arrow alone is 1.39:1. Both viewBoxes are cropped to
// the artwork's real ink bounds — Illustrator's export padded it so heavily
// that `height: 26px` drew the logo about 6px tall. Don't paste a fresh export
// over this without re-cropping it.
//
// Colours are inline `fill` attributes, not Illustrator's .st0/.st1 classes.
// Those class names are global once an SVG is inlined in a page, so two
// Illustrator exports on the same page fight over them and swap colours.
// components/BrandArt.js is another such export, which is why this matters.

// Both viewBoxes carry 2 units of bleed on every side. Cropped exactly to the
// ink bounds — which is how these started — the outermost pixels of the blue
// blade and the final "n" get clipped by sub-pixel rounding, and at small
