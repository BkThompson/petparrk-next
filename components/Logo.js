// Two marks exist and they are not interchangeable. The ARROW is the primary
// company identity and is what the website uses. The PINWHEEL is the compact
// secondary mark, for the app icon, the favicon and social avatars. That split
// was set in the brief to Ashar; don't swap one for the other here.
//
// Three exports:
//   Logo       the full lockup (arrow + wordmark), for the navbar and footer
//   BrandMark  the arrow alone in currentColor, for small brand badges
//   ARROW_VIEWBOX / ARROW_PATHS  the same arrow as raw data, for the one
//              place that builds its SVG by hand (components/HeroFlipCard.js
//              draws with createElementNS so html-to-image can rasterize it)
//
// Logo takes a `variant`:
//   "onDark"  (default) cream wordmark — navy navbar, navy footer
//   "onLight"           navy wordmark — Admin and any white surface
// Only the wordmark and the two cream arrow blades change; the blue, gold and
// terracotta blades are brand colours and stay put in both variants.
//
// The wordmark is cream (#F5F0E8) rather than pure white so it matches the
// cream used everywhere else on the site, and the arrow keeps its brand
